#!/bin/bash
# average.sh – вычисляет среднее целых аргументов, вывод всегда есть

if [ $# -eq 0 ]; then
    echo "Ошибка: не передано ни одного аргумента."
    echo "Использование: $0 <целое1> <целое2> ..."
    exit 1
fi

sum=0
for num in "$@"; do
    sum=$((sum + num))
done

count=$#
whole=$((sum / count))          # целая часть
rem=$((sum % count))            # остаток

# Вычисляем две цифры после запятой (остаток * 100 / количество)
frac=$(( (rem * 100) / count ))

# Если дробная часть меньше 10, добавляем ведущий ноль
if [ $frac -lt 10 ]; then
    frac="0$frac"
fi

echo "Количество чисел: $count"
echo "Среднее арифметическое: $whole.$frac"